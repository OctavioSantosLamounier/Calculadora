    private void btnPorcentagemActionPerformed(java.awt.event.ActionEvent evt) {
        double valorAtual = Double.parseDouble(bufferAtual);
        double fracao = valorAtual / 100.0;

        double resultado;
        switch (operadorPendente) {
            case '+':
            case '-':
                resultado = calcular(valorAnterior, valorAnterior * fracao, operadorPendente);
                break;
            case '*':
            case '/':
                resultado = calcular(valorAnterior, fracao, operadorPendente);
                break;
            default:
                resultado = fracao;
        }

        exibirValor(resultado);
        bufferAtual = String.valueOf(resultado);
        
        valorAnterior = resultado;
        operadorPendente = ' ';
        prontoParaNovoNumero = true;
        temPontoDecimal = false;
    }

    private void btnRaizActionPerformed(java.awt.event.ActionEvent evt) {
        double valorAtual = Double.parseDouble(bufferAtual);
        if (valorAtual < 0) {
            exibirString("Erro");
            resetarEstado();
            return;
        }
        
        double resultado = Math.sqrt(valorAtual);
        
        exibirValor(resultado);
        bufferAtual = String.valueOf(resultado);
        
        prontoParaNovoNumero = true;
        temPontoDecimal = false;
    }

    
    private void btnIgualActionPerformed(java.awt.event.ActionEvent evt) {
        if (operadorPendente == ' ') return;
        
        double valorAtual = Double.parseDouble(bufferAtual);

        if (operadorPendente == '/' && valorAtual == 0) {
            exibirString("Erro");
            resetarEstado();
            return;
        }

        double resultado = calcular(valorAnterior, valorAtual, operadorPendente);
        
        exibirValor(resultado);
        bufferAtual = String.valueOf(resultado);
        
        valorAnterior = resultado;
        operadorPendente = ' '; 
        prontoParaNovoNumero = true;
        temPontoDecimal = false;
    }

    private void btnClearActionPerformed(java.awt.event.ActionEvent evt) {
        resetarEstado();
        exibirString(bufferAtual);
    }

    
    private void btnMpActionPerformed(java.awt.event.ActionEvent evt) {
        memoria += Double.parseDouble(bufferAtual);
        prontoParaNovoNumero = true;
    }

    private void btnMnActionPerformed(java.awt.event.ActionEvent evt) {
        memoria -= Double.parseDouble(bufferAtual);
        prontoParaNovoNumero = true;
    }
    
    private void btnMrcActionPerformed(java.awt.event.ActionEvent evt) {
        if (ultimaAcaoFoiMrc) memoria = 0;

        exibirValor(memoria);
        bufferAtual = String.valueOf(memoria);
        ultimaAcaoFoiMrc = !ultimaAcaoFoiMrc;

        prontoParaNovoNumero = true;
        temPontoDecimal = false;
    }

    
    private void btnOffActionPerformed(java.awt.event.ActionEvent evt) {
        System.exit(0);
    }

    
