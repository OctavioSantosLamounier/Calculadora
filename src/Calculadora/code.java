    private void exibirValor(double valor) {
        if (valor == (long) valor && !Double.isInfinite(valor)) {
            txfDisplay.setText(String.valueOf((long) valor));
        } 
        else {
            txfDisplay.setText(String.valueOf(valor));
        }
    }

    private void exibirString(String str) {
        txfDisplay.setText(str);
    }

    private double calcular(double a, double b, char operador) {
        switch (operador) {
            case '+': return a + b;
            case '-': return a - b;
            case '*': return a * b;
            case '/': return a / b; 
            default: return b;
        }
    }

    private void aplicarOperador(char novoOperador) {
        ultimaAcaoFoiMrc = false;
        double valorAtual = Double.parseDouble(bufferAtual);

        if (operadorPendente != ' ' && !prontoParaNovoNumero) {
            if (operadorPendente == '/' && valorAtual == 0) {
                exibirString("Erro");
                resetarEstado();
                return;
            }
            valorAnterior = calcular(valorAnterior, valorAtual, operadorPendente);
            exibirValor(valorAnterior);
        } 
        else {
            valorAnterior = valorAtual;
        }

        operadorPendente = novoOperador;
        prontoParaNovoNumero = true;
        temPontoDecimal = false;
    }

    private void resetarEstado() {
        bufferAtual = "0";
        valorAnterior = 0;
        operadorPendente = ' ';
        prontoParaNovoNumero = true;
        temPontoDecimal = false;
    }

    private void digitoPressionado(String digito) {
        ultimaAcaoFoiMrc = false;
        
        if (prontoParaNovoNumero) {
            bufferAtual = digito;
            prontoParaNovoNumero = false;
        } 
        else if (bufferAtual.equals("0")) {
            bufferAtual = digito.equals("0") ? "0" : digito;
        } 
        else {
            bufferAtual += digito;
        }
        
        exibirString(bufferAtual);
    }

    
